"""Build the offline browser copy from the two archived OPENSTEP-009 CSVs."""
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def rows(name):
    with (HERE / "results" / name).open(newline="") as handle:
        return list(csv.DictReader(handle))


def key(row):
    if row["degraded"] not in ("True", "False"):
        raise ValueError(f"Unknown cooling schedule in {row}")
    return (row["tag"], float(row["radius_m"]), row["degraded"] == "True")


def export():
    histories = {}
    for row in rows("histories.csv"):
        histories.setdefault(key(row), []).append([float(row["time_s"]), float(row["surface_K"])])
    cases = []
    seen = set()
    for row in rows("cases.csv"):
        identity = key(row)
        if identity in seen:
            raise ValueError(f"Duplicate case {identity}")
        seen.add(identity)
        points = histories.pop(identity)
        sample = row["first_sample_above_1800_s"]
        cases.append(dict(shiftCm=round(float(row["shift_m"])*100), radiusMm=round(identity[1]*1000),
                          degraded=identity[2], peakK=float(row["peak64_K"]),
                          firstAboveS=float(sample) if sample else None,
                          heatMWm2=float(row["heat_MW_m2"]), points=points))
    if len(cases) != 32 or histories:
        raise ValueError("Unexpected OPENSTEP-009 coverage")
    payload = json.dumps(cases, allow_nan=False, separators=(",", ":"))
    return "// Generated by benchmarks/openstep-009/export_browser.py from the archived CSVs.\nconst coolingCases = " + payload + ";\n"


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the published browser copy without writing")
    path = HERE / "browser-data.js"
    content = export()
    if parser.parse_args().check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit("Cooling browser data differ from the archived CSVs")
    else:
        path.write_text(content)
